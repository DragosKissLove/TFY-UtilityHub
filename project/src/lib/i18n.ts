// Ensure complete key coverage for all languages.
// Missing keys in non-English packs automatically fall back to the English value.
(() => {
  const en = dictionary.en;
  (Object.keys(dictionary) as TfyLanguage[]).forEach((lang) => {
    if (lang === 'en') return;
    const target = dictionary[lang];
    Object.keys(en).forEach((key) => {
      if (!target[key]) {
        target[key] = en[key];
      }
    });
  });
})();
export function normalizeLanguage(input?: string | null): TfyLanguage {
  const raw = (input || '').trim().toLowerCase();
  return aliases[raw] || 'en';
}
export function getLanguage(): TfyLanguage {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    const normalized = normalizeLanguage(raw);
    memoryLanguage = normalized;
    return normalized;
  } catch {
    return memoryLanguage;
  }
}
export function setLanguage(language: TfyLanguage) {
  memoryLanguage = language;
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
  }
  window.dispatchEvent(new CustomEvent(EVENT_NAME, { detail: language }));
}
export function isLanguagePackInstalled(language: TfyLanguage) {
  try {
    if (language === 'en') return true;
    const raw = localStorage.getItem(PACKS_KEY);
    const packs = raw ? (JSON.parse(raw) as Record<string, boolean>) : {};
    return Boolean(packs[language]);
  } catch {
    return language === 'en';
  }
}
export function markLanguagePackInstalled(language: TfyLanguage) {
  try {
    const raw = localStorage.getItem(PACKS_KEY);
    const packs = raw ? (JSON.parse(raw) as Record<string, boolean>) : {};
    packs[language] = true;
    localStorage.setItem(PACKS_KEY, JSON.stringify(packs));
  } catch {
  }
}
export function onLanguageChange(callback: (language: TfyLanguage) => void) {
  const handler = (event: Event) => {
    const detail = (event as CustomEvent<TfyLanguage>).detail;
    callback(detail || getLanguage());
  };
  window.addEventListener(EVENT_NAME, handler);
  return () => window.removeEventListener(EVENT_NAME, handler);
}
export function t(language: TfyLanguage, key: string) {
  return dictionary[language][key] || dictionary.en[key] || key;
}


